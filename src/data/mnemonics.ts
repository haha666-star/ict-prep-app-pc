/** 取某知识点的巧记（无则返回空串）；`seq` 为该题在本知识点内的出现序号，用于轮换变体 */
export function mnemonicOf(knowledgeId?: string, seq = 0): string {
  if (!knowledgeId) return '';
  const variants = MNEMONIC_BY_KNOWLEDGE[knowledgeId];
  if (!variants || variants.length === 0) return '';
  const n = variants.length;
  return variants[((Math.trunc(seq) % n) + n) % n] ?? '';
}
